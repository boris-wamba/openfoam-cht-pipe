"""blockMeshDict generation for the axisymmetric (wedge) fluid + wall geometry.

Layout, with x the pipe axis and the wedge centred on the xy plane:

    axial:   [0, L_ENTRY] (unheated)  [L_ENTRY, L_TOTAL] (heated)
    radial:  fluid [0, R_IN], wall [R_IN, R_OUT]

Four hexahedral blocks: fluid-entry, fluid-heated, solid-entry, solid-heated.
The fluid blocks are collapsed onto the axis (repeated vertex labels), so
they become prisms there and no axis patch is needed.
"""
from __future__ import annotations

import math

# OpenFOAM hex model faces, local vertex numbers (outward-pointing normals)
HEX_FACES = {
    "xmin": (0, 4, 7, 3),
    "xmax": (1, 2, 6, 5),
    "ymin": (0, 1, 5, 4),
    "ymax": (3, 7, 6, 2),
    "zmin": (0, 3, 2, 1),
    "zmax": (4, 5, 6, 7),
}


def build(p: dict) -> dict:
    """Vertices, blocks and patches for the case parameters ``p``."""
    th = math.radians(p["HALF_ANGLE_DEG"])
    xs = [0.0, p["L_ENTRY"], p["L_TOTAL"]]
    labels: dict[tuple, int] = {}
    vertices: list[tuple[float, float, float]] = []

    def vertex(kind: str, i: int, side: str) -> int:
        key = (kind, i, side if kind != "ax" else "")
        if key not in labels:
            labels[key] = len(vertices)
            r = {"ax": 0.0, "ri": p["R_IN"], "ro": p["R_OUT"]}[kind]
            z = {"m": -1.0, "p": 1.0, "": 0.0}[key[2]] * r * math.sin(th)
            vertices.append((xs[i], r * math.cos(th), z))
        return labels[key]

    ax = [vertex("ax", i, "") for i in range(3)]
    rim = [vertex("ri", i, "m") for i in range(3)]
    rip = [vertex("ri", i, "p") for i in range(3)]
    rom = [vertex("ro", i, "m") for i in range(3)]
    rop = [vertex("ro", i, "p") for i in range(3)]

    nxs = [p["NX_E"], p["NX_H"]]
    er_wall = 1.0 / p["EXPANSION_TOTAL"]      # cells shrink towards the wall (j increases outward)
    blocks = []
    for i in range(2):
        blocks.append({
            "name": f"fluid_{'entry' if i == 0 else 'heated'}", "zone": "fluid",
            "hex": (ax[i], ax[i + 1], rim[i + 1], rim[i], ax[i], ax[i + 1], rip[i + 1], rip[i]),
            "cells": (nxs[i], p["NR_F"], 1), "grading": (1.0, er_wall, 1.0),
        })
    for i in range(2):
        blocks.append({
            "name": f"solid_{'entry' if i == 0 else 'heated'}", "zone": "solid",
            "hex": (rim[i], rim[i + 1], rom[i + 1], rom[i], rip[i], rip[i + 1], rop[i + 1], rop[i]),
            "cells": (nxs[i], p["NR_S"], 1), "grading": (1.0, 1.0, 1.0),
        })

    def face(block: int, name: str) -> tuple[int, ...]:
        """Face labels exactly as in the (collapsed) hex: repeated labels are kept.

        blockMesh matches patch faces against the block faces, which keep their
        repeated vertices, so a face on the collapsed axis has to be written with
        four labels, e.g. (0 0 6 3), not as a triangle.
        """
        hx = blocks[block]["hex"]
        return tuple(hx[k] for k in HEX_FACES[name])

    patches = [
        ("inlet", "patch", [face(0, "xmin")]),
        ("outlet", "patch", [face(1, "xmax")]),
        ("axis", "empty", [face(0, "ymin"), face(1, "ymin")]),   # fully collapsed faces, no cells face
        ("outer_unheated", "wall", [face(2, "ymax")]),
        ("outer_heated", "wall", [face(3, "ymax")]),
        ("solid_inlet", "wall", [face(2, "xmin")]),
        ("solid_outlet", "wall", [face(3, "xmax")]),
        ("front", "wedge", [face(b, "zmax") for b in range(4)]),
        ("back", "wedge", [face(b, "zmin") for b in range(4)]),
    ]
    # the fluid/solid interfaces are internal faces here: splitMeshRegions turns them into patches
    return {"vertices": vertices, "blocks": blocks, "patches": patches}


def write(p: dict, path) -> dict:
    """Write ``blockMeshDict`` to ``path``; returns the geometry dict."""
    geo = build(p)
    lines = [
        "FoamFile",
        "{",
        "    version     2.0;",
        "    format      ascii;",
        "    class       dictionary;",
        "    object      blockMeshDict;",
        "}",
        "",
        f"// Generated by chtpipe for case {p['name']} - do not edit by hand.",
        "scale   1;",
        "",
        "vertices",
        "(",
    ]
    for k, (x, y, z) in enumerate(geo["vertices"]):
        lines.append(f"    ({x:.10g} {y:.10g} {z:.10g})   // {k}")
    lines += [");", "", "blocks", "("]
    for b in geo["blocks"]:
        hx = " ".join(str(v) for v in b["hex"])
        nx, ny, nz = b["cells"]
        gx, gy, gz = b["grading"]
        lines.append(
            f"    hex ({hx}) {b['zone']} ({nx} {ny} {nz}) "
            f"simpleGrading ({gx:.10g} {gy:.10g} {gz:.10g})   // {b['name']}"
        )
    lines += [");", "", "edges", "(", ");", "", "boundary", "("]
    for name, ptype, faces in geo["patches"]:
        lines.append(f"    {name}")
        lines.append("    {")
        lines.append(f"        type {ptype};")
        lines.append("        faces")
        lines.append("        (")
        for f in faces:
            lines.append("            (" + " ".join(str(v) for v in f) + ")")
        lines.append("        );")
        lines.append("    }")
    lines += [");", "", "mergePatchPairs", "(", ");", ""]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))
    return geo
